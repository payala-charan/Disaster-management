"""Generate docs/METHODOLOGY.md from the module docstrings of the rule-bearing modules.

    python -m app.tools.gen_docs

The docstrings ARE the documentation of every deterministic rule, so the methodology document can
never drift from the code that implements it. Re-run after changing a rule.
"""

import importlib
import inspect

from app.core.config import BACKEND_DIR

SECTIONS: list[tuple[str, list[tuple[str, str]]]] = [
    ("Deterministic engines (no LLM)", [
        ("Priority score", "app.engines.priority"),
        ("Zone accessibility", "app.engines.access"),
        ("Duplicate detection", "app.engines.duplicates"),
        ("Resource state machine and requirement estimation", "app.engines.resources"),
        ("Shelter calculations", "app.engines.shelters"),
        ("Allocation and alternative plans", "app.engines.allocation"),
        ("Replanning impact analysis", "app.engines.replanning"),
        ("Distance and travel estimates", "app.engines.geo"),
    ]),
    ("Integrations", [
        ("LLM (OpenAI) usage and fallback", "app.integrations.llm"),
        ("Grounding check", "app.integrations.grounding"),
        ("Fallback extractor", "app.integrations.fallback_extract"),
        ("Weather (Open-Meteo)", "app.integrations.weather"),
        ("Routing (OSRM)", "app.integrations.routing"),
        ("Geocoding", "app.integrations.geocoding"),
    ]),
    ("Agents and orchestration", [
        ("Workflow graph", "app.graph.workflow"),
        ("Shared workflow state", "app.graph.state"),
        ("Agent machinery and trace", "app.agents.base"),
        ("1. Incident Intake", "app.agents.intake"),
        ("2. Situation Assessment & Severity", "app.agents.severity"),
        ("3. Weather & Environmental Intelligence", "app.agents.weather_intel"),
        ("4. Geospatial & Accessibility", "app.agents.geospatial"),
        ("5. Emergency Resource Management", "app.agents.resource_mgmt"),
        ("6. Resource Allocation & Response Planning", "app.agents.planning"),
        ("7. Emergency Coordination & Action", "app.agents.coordination"),
        ("8. Reviewer / Critic", "app.agents.critic"),
    ]),
    ("Services (API side)", [
        ("Human approval workflow", "app.services.actions"),
        ("Dynamic replanning", "app.services.replanning"),
        ("Operational changes and alert rules", "app.services.operations"),
        ("Overdue actions", "app.services.overdue"),
        ("Situation report PDF", "app.services.reports"),
        ("Simulation controls", "app.services.simulation"),
    ]),
]


def build() -> str:
    out = ["# Methodology (generated)", "",
           "Generated by `python -m app.tools.gen_docs` from the module docstrings: the code and this document "
           "describe the same rules. Do not edit by hand.", ""]
    for title, modules in SECTIONS:
        out += [f"## {title}", ""]
        for name, module in modules:
            doc = inspect.getdoc(importlib.import_module(module)) or "(no docstring)"
            path = module.replace(".", "/") + ".py"
            out += [f"### {name}", "", f"Source: [`backend/{path}`](../backend/{path})", "", doc, ""]
    return "\n".join(out)


if __name__ == "__main__":
    target = BACKEND_DIR.parent / "docs" / "METHODOLOGY.md"
    target.write_text(build())
    print(f"Wrote {target}")
