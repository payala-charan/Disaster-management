"""Situation report PDF (ReportLab). Sections, in order:

 1. Situation summary (narrative: LLM grounded in the snapshot, or the deterministic template)
 2. Incident summary            3. Affected locations           4. Priority assessment
 5. Weather conditions          6. Accessibility                7. Available resources
 8. Deployed / reserved resources                               9. Resource shortages
10. Shelter status             11. Recommended actions         12. Pending approvals
13. Completed actions          14. Data uncertainties          15. Assessment timestamp
plus the safety disclaimer on every page.

Every table is built from the database snapshot. The narrative is the only generated text and it
passes the grounding check (no ID or number that is not in the snapshot).
"""

from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.db import models as m
from app.db.repository import next_id, road_facts
from app.engines.access import assess_zone_access
