DISCLAIMER = ("DECISION SUPPORT ONLY. This report is generated by an AI-assisted prototype. All actions require "
              "approval by an authorized coordinator. Verify reported and inferred information before acting.")
STYLES = getSampleStyleSheet()
SMALL = ParagraphStyle("small", parent=STYLES["BodyText"], fontSize=8, leading=10)


def _p(text: str, style=SMALL) -> Paragraph:
    return Paragraph(str(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"), style)


def _table(header: list[str], rows: list[list[str]], widths: list[float] | None = None) -> Table:
    data = [[_p(h, ParagraphStyle("h", parent=SMALL, fontName="Helvetica-Bold")) for h in header]]
    data += [[_p(c) for c in row] for row in rows] or [[_p("None")] + [_p("")] * (len(header) - 1)]
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e293b")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#94a3b8")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return t


def _footer(canvas, doc) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica-Oblique", 7)
    canvas.setFillColor(colors.HexColor("#b45309"))
    canvas.drawString(15 * mm, 10 * mm, DISCLAIMER[:150])
    canvas.drawRightString(195 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def build_pdf(path, title: str, generated_at: datetime, narrative: str, narrative_llm: bool,
              snap: s.SituationSnapshot, plan: s.Plan | None, access: dict[str, str]) -> None:
    H = STYLES["Heading2"]
    story: list = [Paragraph(title, STYLES["Title"]),
                   _p(DISCLAIMER, ParagraphStyle("d", parent=SMALL, textColor=colors.HexColor("#b45309"))),
                   Spacer(1, 4 * mm)]

    def section(name, *flowables):
        story.extend([Paragraph(name, H), *flowables, Spacer(1, 3 * mm)])

    incidents = sorted(snap.incidents, key=lambda i: -(i.priority.score if i.priority else -1))
    section("1. Situation summary", _p(narrative, STYLES["BodyText"]),
            _p("(Narrative: AI-generated, grounding-checked)" if narrative_llm else "(Narrative: deterministic template)"))
    section("2. Incident summary", _table(
        ["ID", "Type", "Title", "People", "Source", "Verification"],
        [[i.id, i.type, i.title, str(i.people_affected) if i.people_affected is not None else "Unknown (verify)",
          i.source, i.verification_status + (f"; possible duplicate of {i.duplicate_of}" if i.duplicate_of else "")]
         for i in incidents], [18 * mm, 22 * mm, 55 * mm, 22 * mm, 28 * mm, 35 * mm]))
    section("3. Affected locations", _table(
        ["ID", "Zone", "Coordinates"],
        [[i.id, i.zone, f"{i.location.lat:.4f}, {i.location.lng:.4f}" if i.location else "Unknown: verification required"]
         for i in incidents]))
    section("4. Priority assessment", _table(
        ["ID", "Score", "Level", "Main factors"],
        [[i.id, str(i.priority.score) if i.priority else "-", i.priority.level if i.priority else "not assessed",
          "; ".join(i.priority.reasons[:3]) if i.priority else ""] for i in incidents],
        [18 * mm, 15 * mm, 30 * mm, 117 * mm]))
    section("5. Weather conditions", _table(
        ["Zone", "Condition", "Rain mm/h", "Wind km/h", "Severe", "Outlook", "Source"],
        [[w.zone, w.condition, f"{w.rainfall_mm_per_hr:g}", f"{w.wind_kph:g}", "yes" if w.severe_warning else "no",
          w.forecast_summary, w.source] for w in snap.weather]))
    section("6. Accessibility (road registry; inferred issues listed separately)", _table(
        ["Road", "Zone", "Status", "Provenance", "Note"],
        [[r.id + " " + r.name, r.serves_zone, r.status, r.provenance.upper(), r.note or ""] for r in snap.roads]),
        _p("Zone access: " + "; ".join(f"{z}: {a}" for z, a in sorted(access.items()))))
    avail = [r for r in snap.resources if r.status == "available"]
    by_type: dict[str, int] = {}
    for r in avail:
        by_type[r.type] = by_type.get(r.type, 0) + 1
    section("7. Available resources", _table(["Type", "Available"], [[t, str(n)] for t, n in sorted(by_type.items())]))
    section("8. Deployed / reserved / returning resources", _table(
        ["ID", "Type", "Status", "Incident", "Expected available"],
        [[r.id, r.type, r.status, r.assigned_incident_id or "-",
          r.expected_available_at.strftime("%H:%M UTC") if r.expected_available_at else "-"]
         for r in snap.resources if r.status not in ("available",)]))
    section("9. Resource shortages", _table(
        ["Type", "Required", "Available", "Deficit", "Incidents", "Escalation"],
        [[x.resource_type, str(x.required), str(x.available), str(x.deficit), ", ".join(x.incident_ids), x.note]
         for x in snap.shortages]))
    section("10. Shelter status", _table(
        ["Shelter", "Capacity", "Occupancy", "Available", "Utilization", "Status"],
        [[f"{sh.id} {sh.name}", str(sh.capacity), str(sh.current_occupancy), str(shelter_available(sh)),
          f"{utilization(sh):.0%}", sh.status] for sh in snap.shelters]))
    section("11. Recommended actions" + (f" ({plan.id}: {plan.title})" if plan else ""),
            _p(plan.explanation if plan else "No current recommendation."))
    by_status = lambda *st: [a for a in snap.actions if a.status in st]  # noqa: E731
    action_rows = lambda acts: [[a.id, a.incident_id, ", ".join(a.resource_ids), a.priority, a.status] for a in acts]  # noqa: E731
    section("12. Pending approvals", _table(["Action", "Incident", "Resources", "Priority", "Status"],
                                            action_rows(by_status("pending"))))
    section("13. Approved, in-progress and completed actions",
            _table(["Action", "Incident", "Resources", "Priority", "Status"],
                   action_rows(by_status("approved", "in_progress", "completed"))))
    uncertainties = sorted({v for i in incidents if i.priority for v in i.priority.verification_needed}
                           | {f"{r.id} {r.name}: inferred, {r.note or 'unconfirmed'}" for r in snap.roads if r.provenance == "inferred"}
                           | {f"{i.id}: people affected not reported" for i in incidents if i.people_affected is None})
    section("14. Data uncertainties", *[_p("- " + u) for u in uncertainties] or [_p("None recorded")])
    section("15. Assessment timestamp", _p(f"Generated {generated_at.strftime('%Y-%m-%d %H:%M:%S UTC')}; "
                                           f"latest assessment run {plan.run_id if plan else 'none'}"))

    SimpleDocTemplate(str(path), pagesize=A4, title=title, leftMargin=15 * mm, rightMargin=15 * mm,
                      topMargin=15 * mm, bottomMargin=18 * mm).build(story, onFirstPage=_footer, onLaterPages=_footer)


def generate(svc: Services, db: Session) -> m.SituationReport:
    now = svc.now()
    snap = ser.situation(db)
    plan_row = ser.current_recommended_plan(db)
    plan = ser.plan(plan_row) if plan_row else None
    roads = road_facts(db)
    access = {z: assess_zone_access(z, roads).status for z in {i.zone for i in snap.incidents}}

    compact = {  # what the narrative may draw from (and is grounding-checked against)
        "incidents": [i.model_dump(mode="json", include={"id", "title", "zone", "people_affected", "priority"}) for i in snap.incidents],
        "access": access, "shortages": [x.model_dump(mode="json") for x in snap.shortages],
        "weather": [w.model_dump(mode="json") for w in snap.weather],
        "shelters": [sh.model_dump(mode="json", exclude={"location"}) for sh in snap.shelters],
        "actions": [a.model_dump(mode="json", include={"id", "incident_id", "status", "resource_ids"}) for a in snap.actions],
    }
    narrative = svc.deps.llm.sitrep_narrative(compact)

    report_id = next_id(db, m.SituationReport, "SR")
    svc.settings.reports_dir.mkdir(parents=True, exist_ok=True)
    file_name = f"{report_id}.pdf"
    title = f"Situation Report {report_id}"
    build_pdf(svc.settings.reports_dir / file_name, title, now, narrative.text, narrative.llm_used and narrative.grounded,
              snap, plan, access)
    row = m.SituationReport(id=report_id, title=title, generated_at=now, run_id=plan.run_id if plan else None,
                            narrative=narrative.text, narrative_llm=narrative.llm_used and narrative.grounded,
                            file_name=file_name)
    db.add(row)
    db.commit()
    return row


def meta(row: m.SituationReport) -> s.SituationReportDetail:
    return s.SituationReportDetail(id=row.id, title=row.title, generated_at=row.generated_at, run_id=row.run_id,
                                   pdf_url=f"/api/reports/{row.id}/pdf", narrative=row.narrative,
                                   narrative_llm=row.narrative_llm)


def list_reports(db: Session) -> list[s.SituationReportDetail]:
    return [meta(r) for r in db.scalars(select(m.SituationReport).order_by(m.SituationReport.generated_at.desc()))]
